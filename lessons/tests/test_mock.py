"""
Теперь наши тесты умеют проверять ожидаемое поведение, 
перебирать наборы данных и переиспользовать подготовительный 
код. Но есть одна тонкость, которая рано или поздно встаёт перед 
каждым разработчиком: как тестировать код, который 
взаимодействует с «внешним миром»? 

Представьте, что вы пишете функцию, которая: 
• Ходит по HTTP к платежному шлюзу; 
• Читает конфигурацию из файла на диске; 
• Отправляет запрос в базу данных; 
• Парсит JSON или CSV файл на тысячи строк.


Хотя в повседневной речи эти термины часто смешивают, 
полезно их различать: 
• Заглушка (Stub): Это простой объект, который предоставляет 
предопределенные ("зашитые") ответы на вызовы методов во 
время теста. Заглушки используются, когда тесту нужны какие
то данные от зависимости, но сама зависимость не является 
объектом проверки. 

Пример: Заглушка для сервиса, возвращающего погоду, 
всегда отдает {"temperature": 25, "condition": "sunny"}. 

• Мок (Mock): Это более "умный" объект. Моки не только 
предоставляют ответы (как заглушки), но и позволяют вам 
проверять, как ваш код взаимодействовал с этой 
зависимостью. Вы можете настроить ожидания (например, 
какой метод должен быть вызван, с какими аргументами, 
сколько раз) и затем проверить, были ли эти ожидания 
выполнены. 

Пример: Мок для сервиса отправки email, который 
позволяет проверить, что метод send_email был вызван 
ровно один раз с правильным адресом получателя и темой 
письма.
"""


# МОКИ И ЗАГЛУШКИ 
from unittest.mock import Mock, MagicMock


class PaymentService:
    def debit(self) -> bool:
        """Списание денег со счёта."""
        pass

    def log_transaction(self):
        pass


def process_payment(payment_service: PaymentService, amount: float): 
    # Пытаемся провести операцию по списанию 
    is_success = payment_service.debit(amount) 
 
    if is_success: 
        # Если оплата прошла успешно 
        payment_service.log_transaction(details=f"Debit {amount}") 
        return "SUCCESS" 
    else: 
        # Если оплата не прошла 
        return "FAILED"


def test_process_payment_success(): 
     # Создаём мок для payment_service 
    mock_payment_service = Mock()

    # Настраиваем мок, при вызове метода debit, он должен вернуть True. 
    mock_payment_service.debit.return_value = True

    # Вызываем тестируемую функцию, но с моком 
    result = process_payment(mock_payment_service, 500)
    
    # Проверяем результат выполнения функции 
    assert result == "SUCCESS" 

    


