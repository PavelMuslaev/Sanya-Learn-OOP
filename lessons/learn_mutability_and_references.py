# =============================================================================
# __add__ И СОЗДАНИЕ НОВОГО ОБЪЕКТА
#
# Оператор + вызывает специальный метод __add__.
#
# Для списка выражение:
#
#     nums + [1, 2, 3]
#
# не изменяет существующий список nums.
# Вместо этого Python создаёт НОВЫЙ список, содержащий элементы обоих списков.
#
# Поэтому после присваивания:
#
#     nums = nums + [1, 2, 3]
#
# переменная nums начинает ссылаться уже на другой объект.
#
# Это можно увидеть с помощью id():
# идентификатор объекта до и после операции будет разным.
# =============================================================================

nums = [1, 2, 3, 4, 5]

print(id(nums))

nums = nums + [1, 2, 3]

print(id(nums))
print()


# =============================================================================
# __iadd__ И ИЗМЕНЕНИЕ СУЩЕСТВУЮЩЕГО ОБЪЕКТА
#
# Оператор += пытается вызвать специальный метод __iadd__.
#
# Для изменяемых объектов, например list, __iadd__ обычно изменяет
# существующий объект, а не создаёт новый.
#
# Поэтому:
#
#     nums += [1, 2, 3]
#
# фактически расширяет текущий список.
#
# Переменная nums продолжает ссылаться на тот же объект,
# поэтому его id остаётся прежним.
#
# Для list поведение += примерно соответствует:
#
#     nums.extend([1, 2, 3])
# =============================================================================

nums = [1, 2, 3, 4, 5]

print(id(nums))

nums += [1, 2, 3]

print(id(nums))
print()


# =============================================================================
# НЕИЗМЕНЯЕМЫЕ ОБЪЕКТЫ И +=
#
# str является НЕИЗМЕНЯЕМЫМ типом данных.
#
# Это означает, что существующую строку нельзя изменить после её создания.
#
# Поэтому выражение:
#
#     text += "sdd"
#
# не может изменить строку "ddd".
#
# Python создаёт новую строку "dddsdd", после чего переменная text
# начинает ссылаться на новый объект.
#
# Следовательно, id изменяется.
#
# Важно:
# наличие оператора += ещё не означает, что объект будет изменён на месте.
# Всё зависит от реализации типа и его изменяемости.
# =============================================================================

text = "ddd"

print(id(text))

text += "sdd"

print(id(text))
print()


# =============================================================================
# += ДЛЯ TUPLE
#
# tuple, как и str, является неизменяемым типом данных.
#
# Поэтому кортеж нельзя расширить "на месте".
#
# При выполнении:
#
#     nums *= 3
#
# Python создаёт новый кортеж, содержащий повторённые элементы,
# и переменная nums начинает ссылаться уже на него.
#
# Для неизменяемых объектов операции += и *= обычно приводят
# к созданию нового объекта.
# =============================================================================

nums = (1, 2, 3)

nums *= 3

print(nums)
print()


# =============================================================================
# ПРОБЛЕМА ВЛОЖЕННЫХ КОЛЛЕКЦИЙ И КОПИРОВАНИЯ
#
# Коллекции могут содержать внутри себя другие изменяемые объекты.
#
# Например, список info содержит:
#
#     1. список;
#     2. строку;
#     3. множество.
#
# Если просто скопировать внешний список недостаточно глубоко,
# вложенные изменяемые объекты могут остаться общими для оригинала
# и копии.
#
# copy.deepcopy() выполняет ГЛУБОКОЕ КОПИРОВАНИЕ:
# создаётся не только новый внешний список, но и независимые копии
# вложенных изменяемых объектов.
#
# Поэтому изменение:
#
#     info_copy[0][1] = 10
#
# не затронет вложенный список внутри исходного info.
# =============================================================================

import copy

info = [[1, 2, 3], "dddd", {1, 2, 3}]

info_copy = copy.deepcopy(info)

info_copy[1] = "aaa"
info_copy[0][1] = 10

print(info_copy)
print(info)
print()


# =============================================================================
# ПРОБЛЕМА ОДИНАКОВЫХ ССЫЛОК ПРИ УМНОЖЕНИИ ВЛОЖЕННОГО СПИСКА
#
# Рассмотрим выражение:
#
#     [[0] * 3] * 3
#
# Сначала создаётся ОДИН внутренний список:
#
#     [0, 0, 0]
#
# Затем оператор * не создаёт три независимых внутренних списка.
# Он три раза помещает ССЫЛКУ на один и тот же список.
#
# Схематично:
#
# nums
#   |
#   +----> [0, 0, 0]
#   |
#   +----> тот же объект
#   |
#   +----> тот же объект
#
# Поэтому изменение:
#
#     nums[1][1] = 1
#
# видно сразу во всех трёх строках.
#
# Меняется один общий внутренний объект.
# =============================================================================

nums = [[0] * 3] * 3

print(nums)

nums[1][1] = 1

print(nums)
print()


# =============================================================================
# ПРАВИЛЬНОЕ СОЗДАНИЕ НЕЗАВИСИМЫХ ВЛОЖЕННЫХ СПИСКОВ
#
# Чтобы каждая строка матрицы была отдельным объектом,
# внутренний список нужно СОЗДАВАТЬ ЗАНОВО на каждой итерации.
#
# Для этого удобно использовать list comprehension:
#
#     [[0] * 3 for i in range(3)]
#
# Выражение:
#
#     [0] * 3
#
# выполняется три отдельных раза.
#
# В результате появляются три разных списка:
#
# nums
#   |
#   +----> [0, 0, 0]
#   |
#   +----> [0, 0, 0]
#   |
#   +----> [0, 0, 0]
#
# Теперь изменение nums[1][1] затронет только второй внутренний список.
# =============================================================================

nums = [[0] * 3 for i in range(3)]

print(nums)

nums[1][1] = 1

print(nums)